
import { GoogleGenAI, Modality } from "@google/genai";
import { fileToBase64AndMime } from '../utils/fileUtils';

const PROMPT = `Generate a photorealistic, professional headshot suitable for a LinkedIn profile, based on the provided image. 
The subject should be dressed in professional business attire, such as a dark suit and a light-colored dress shirt. 
Change the background to a soft-focus, neutral office or studio setting. 
Ensure the subject's facial features, expression, and likeness are accurately preserved. 
The final image must be in full color and have a 1:1 aspect ratio.`;

export const generateProfessionalImage = async (file: File): Promise<string> => {
  if (!process.env.API_KEY) {
    throw new Error("API_KEY environment variable is not set.");
  }
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });
  
  try {
    const { base64, mimeType } = await fileToBase64AndMime(file);

    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash-image-preview',
      contents: {
        parts: [
          {
            inlineData: {
              data: base64,
              mimeType: mimeType,
            },
          },
          {
            text: PROMPT,
          },
        ],
      },
      config: {
        responseModalities: [Modality.IMAGE, Modality.TEXT],
      },
    });

    const imagePart = response.candidates?.[0]?.content?.parts?.find(part => part.inlineData);

    if (imagePart && imagePart.inlineData) {
      const base64ImageData = imagePart.inlineData.data;
      const imageMimeType = imagePart.inlineData.mimeType;
      return `data:${imageMimeType};base64,${base64ImageData}`;
    } else {
      // Check for safety ratings or other reasons for no image
      const rejectionReason = response.candidates?.[0]?.finishReason;
      if(rejectionReason === 'SAFETY' || rejectionReason === 'RECITATION' || rejectionReason === 'OTHER') {
        throw new Error(`Image generation failed due to safety policies or other restrictions. Reason: ${rejectionReason}`);
      }
      throw new Error("No image was generated by the API. The prompt may have been blocked or the response format was unexpected.");
    }
  } catch (error) {
    console.error("Error calling Gemini API:", error);
    throw new Error("Failed to generate image. Please check the console for more details.");
  }
};